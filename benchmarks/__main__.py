"""
Run every deterministic benchmark and write the results.

    python -m benchmarks           # regenerate results/results.json and results/summary.md
    python -m benchmarks --check   # exit 1 if the committed results differ from a fresh run

No network, no API keys, no LLM calls.  See benchmarks/README.md.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import logging
import sys
from pathlib import Path
from typing import Any

from benchmarks import chunking, privacy, provenance

HERE = Path(__file__).parent
CUAD = HERE / "fixtures" / "cuad_test.json.gz"
RESULTS = HERE / "results" / "results.json"
SUMMARY = HERE / "results" / "summary.md"
GITHUB = "https://github.com/Quiet-Signals-Lab/Contractex-Legal-Tech-Library"
README = HERE.parent / "README.md"
README_START, README_END = "<!-- benchmarks:start -->", "<!-- benchmarks:end -->"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def collect() -> dict[str, Any]:
    contracts = json.loads(gzip.decompress(CUAD.read_bytes()))["contracts"]
    return {
        "fixtures": {
            CUAD.name: sha256(CUAD),
            privacy.FIXTURE.name: sha256(privacy.FIXTURE),
        },
        "cuad": {
            "contracts": len(contracts),
            "spans": sum(len(c["spans"]) for c in contracts),
            "characters": sum(len(c["text"]) for c in contracts),
        },
        "chunking": chunking.run(contracts),
        "provenance": provenance.run(contracts),
        "privacy": privacy.run(),
    }


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def table(header: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render(r: dict[str, Any]) -> str:
    ch, pv, pr = r["chunking"], r["provenance"], r["privacy"]
    size = ch["breakdown_size"]
    names = list(ch["by_length"])
    out = [
        "## Results",
        "",
        "Generated by `python -m benchmarks`; do not edit by hand.  Methodology and",
        f"limitations: [benchmarks/README.md]({GITHUB}/blob/main/benchmarks/README.md).",
        "",
        f"CUAD v1 test split: {r['cuad']['contracts']} contracts, {r['cuad']['spans']} gold "
        f"answer spans, {r['cuad']['characters']:,} characters.",
        "",
        "### Chunk integrity",
        "",
        "Share of gold clause spans that fall wholly inside one chunk (overlap 0).",
        "",
        table(
            [
                "Chunker",
                "Size (tokens)",
                "Spans intact",
                "Integrity",
                "Chunks",
                "Mean chunk tokens",
                "Chunks over size",
            ],
            [
                [
                    row["chunker"],
                    row["size"],
                    f"{row['spans_intact']} / {row['spans_scored']}",
                    pct(row["spans_intact"], row["spans_scored"]),
                    row["chunks"],
                    row["mean_chunk_tokens"],
                    row["chunks_over_size"],
                ]
                for row in ch["rows"]
            ],
        ),
        "",
        "Spans longer than the chunk size are excluded from that size's score: "
        + ", ".join(
            f"{row['spans_longer_than_chunk']} at {row['size']}"
            for row in ch["rows"]
            if row["chunker"] == names[0]
        )
        + ".",
        "",
        f"#### By span length at {size} tokens",
        "",
        table(
            ["Span length (chars)", *names],
            [
                [f"{lo}-{hi}" if hi < 10**9 else f"{lo}+"]
                + [pct(*ch["by_length"][n][k]) + f" (n={ch['by_length'][n][k][1]})" for n in names]
                for k, (lo, hi) in enumerate(ch["length_buckets"])
            ],
        ),
        "",
        f"#### Categories where clause_aware does not beat every baseline at {size} tokens",
        "",
    ]
    ca = ch["by_category"]["clause_aware"]
    behind = []
    for cat, (ok, n) in sorted(ca.items()):
        others = {k: ch["by_category"][k][cat] for k in names if k != "clause_aware"}
        if any(o[0] / o[1] >= ok / n for o in others.values()):
            behind.append(
                [cat, n, pct(ok, n)] + [pct(*others[k]) for k in names if k != "clause_aware"]
            )
    out += [
        table(
            ["Category", "Spans", "clause_aware", *[k for k in names if k != "clause_aware"]],
            behind,
        ),
        "",
        f"#### Why clause_aware splits a span at {size} tokens",
        "",
        table(
            ["Reason", "Spans"],
            [[k, v] for k, v in ch["failure_reasons"].get("clause_aware", {}).items()],
        ),
        "",
        "### Provenance",
        "",
        f"ProvenanceTracker over ClauseAwareChunker chunks ({pv['chunk_size']} tokens, overlap "
        f"{pv['overlap']}).  *Correct*: the SourceSpan overlaps the gold span.  *Exact*: "
        "`source[span] == value`.  "
        f"{pv['values_whose_text_occurs_earlier']} values also occur earlier in their contract, "
        "so a first-occurrence match points elsewhere.",
        "",
        table(
            ["Mode", "Value as returned", "Resolved", "Correct", "Exact"],
            [
                [
                    mode,
                    variant,
                    pct(c["resolved"], c["values"]),
                    pct(c["correct"], c["values"]),
                    pct(c["exact"], c["values"]),
                ]
                for mode, variants in pv["counts"].items()
                for variant, c in variants.items()
            ],
        ),
        "",
        "### Privacy",
        "",
        f"#### PII detection ({pr['detection']['backend']})",
        "",
        "Planted values whose every letter and digit was redacted.",
        "",
    ]
    variants = sorted({v for vs in pr["detection"]["caught"].values() for v in vs})
    out += [
        table(
            ["Entity", *variants],
            [
                [ent] + [f"{vs[v][0]} / {vs[v][1]}" if v in vs else "" for v in variants]
                for ent, vs in sorted(pr["detection"]["caught"].items())
            ],
        ),
        "",
        f"False positives on non-PII distractors: {pr['detection']['distractor_false_positives']} "
        f"of {pr['detection']['distractors']}.  EvalHarness.run_privacy() on the supported "
        f"cases: entity-type recall {pr['detection']['harness_entity_type_recall']:.1%}, "
        f"precision {pr['detection']['harness_entity_type_precision']:.1%}.",
        "",
        "#### Routing matrix",
        "",
        f"{pr['routing']['passed']} of {pr['routing']['total']} cells match the policy.  "
        f"EvalHarness blocking accuracy: {pr['routing']['harness_blocking_accuracy']:.0%}.",
        "",
        table(
            ["Entry point", "Sensitivity", "Cloud provider", "LocalProvider"],
            [
                [entry, sens]
                + [
                    next(
                        (c["observed"] + ("" if c["pass"] else " (FAIL)"))
                        for c in pr["routing"]["cells"]
                        if c["entry_point"] == entry
                        and c["sensitivity"] == sens
                        and c["provider"] == p
                    )
                    for p in ("cloud", "local")
                ]
                for entry in dict.fromkeys(c["entry_point"] for c in pr["routing"]["cells"])
                for sens in ("public", "confidential", "restricted", "secret")
            ],
        ),
        "",
    ]
    return "\n".join(out)


def readme_block(r: dict[str, Any]) -> str:
    """The generated results table embedded in the top-level README."""
    ch, pv, pr = r["chunking"], r["provenance"], r["privacy"]
    size = ch["breakdown_size"]
    integrity = {
        row["chunker"]: pct(row["spans_intact"], row["spans_scored"])
        for row in ch["rows"]
        if row["size"] == size
    }
    verbatim = pv["counts"]["source_text"]["verbatim"]
    return "\n".join(
        [
            README_START,
            table(
                ["Measured on", "Result"],
                [
                    [
                        f"Gold clause spans kept in one chunk ({r['cuad']['contracts']} CUAD "
                        f"contracts, {size}-token chunks)",
                        " · ".join(f"{k.replace('_', ' ')} {v}" for k, v in integrity.items()),
                    ],
                    [
                        "Verbatim values traced to the right place in the source",
                        pct(verbatim["correct"], verbatim["values"]),
                    ],
                    [
                        "Privacy routing checks (4 sensitivity levels × 2 providers × 4 entry points)",
                        f"{pr['routing']['passed']} of {pr['routing']['total']} pass",
                    ],
                ],
            ),
            README_END,
        ]
    )


def with_readme_block(readme: str, block: str) -> str:
    start, end = readme.index(README_START), readme.index(README_END) + len(README_END)
    return readme[:start] + block + readme[end:]


def main() -> int:
    logging.disable(logging.WARNING)
    results = collect()
    rendered_json = json.dumps(results, indent=1, sort_keys=True) + "\n"
    rendered_md = render(results)
    readme = README.read_text(encoding="utf-8")
    rendered_readme = with_readme_block(readme, readme_block(results))
    if "--check" in sys.argv:
        stale = [
            p.name
            for p, fresh in (
                (RESULTS, rendered_json),
                (SUMMARY, rendered_md),
                (README, rendered_readme),
            )
            if not p.exists() or p.read_text(encoding="utf-8") != fresh
        ]
        if stale:
            print(f"stale benchmark results: {', '.join(stale)}; run python -m benchmarks")
            return 1
        print("benchmark results are up to date")
        return 0
    RESULTS.write_text(rendered_json, encoding="utf-8")
    SUMMARY.write_text(rendered_md, encoding="utf-8")
    README.write_text(rendered_readme, encoding="utf-8")
    print(f"wrote {RESULTS}, {SUMMARY} and the README results table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
